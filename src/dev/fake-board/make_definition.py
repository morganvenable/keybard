#!/usr/bin/env python3
"""
Writes definition.generated.ts: the keyboard definition the simulated Svalboard
sends (Sval DEFINITION_SIZE / DEFINITION_CHUNK), compressed exactly the way the
firmware build does it (modules/svalboard/core/sval_compress.py: the JSON
minified with separators (',', ':'), then lzma FORMAT_ALONE, preset 9).

Usage, from the Keybard repo root:
  python src/dev/fake-board/make_definition.py <path to keymaps/sval/sval.json>
"""
import base64
import json
import lzma
import os
import sys


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    src = sys.argv[1]
    with open(src, "r", encoding="utf-8") as f:
        data = json.load(f)
    json_bytes = json.dumps(data, separators=(",", ":")).encode("utf-8")
    compressed = lzma.compress(json_bytes, format=lzma.FORMAT_ALONE, preset=9)
    b64 = base64.b64encode(compressed).decode("ascii")
    lines = [b64[i:i + 100] for i in range(0, len(b64), 100)]
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "definition.generated.ts")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by make_definition.py from svalboard/qmk keyboards/svalboard/keymaps/sval/sval.json\n")
        f.write("// (the combo-labels firmware branch). Do not edit; run the script again.\n")
        f.write(f"// {len(json_bytes)} bytes of JSON, {len(compressed)} bytes compressed (raw LZMA, as the firmware sends it).\n")
        f.write("export const DEFINITION_LZMA_BASE64 =\n")
        f.write(" +\n".join(f'    "{line}"' for line in lines))
        f.write(";\n")
    print(f"{src}: {len(json_bytes)} -> {len(compressed)} bytes -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
