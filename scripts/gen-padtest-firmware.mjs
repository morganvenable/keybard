// node scripts/gen-padtest-firmware.mjs <dir>
// <dir>/pins.json: [{ "tag", "kind", "fwVersion", "file" }]; the files sit beside it.
// Writes src/generated/padtest-firmware.ts: each file as base64, with its pin.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
const pins = JSON.parse(readFileSync(join(dir, "pins.json"), "utf8"));
const out = [];
const files = {};
for (const p of pins) {
    const bytes = readFileSync(join(dir, p.file));
    out.push({
        tag: p.tag, kind: p.kind, fwVersion: p.fwVersion, updaterProtocol: 4, svalProtocol: 3,
        file: { uf2: p.file, sha256: createHash("sha256").update(bytes).digest("hex"), size: bytes.length },
        notesUrl: p.notesUrl ?? "",
    });
    files[p.tag] = bytes.toString("base64");
}
writeFileSync("src/generated/padtest-firmware.ts",
`import type { FirmwareReleasePin } from "@/constants/firmware-releases";

// Generated by scripts/gen-padtest-firmware.mjs: the firmware files the test build carries.
export const PADTEST_PINS: FirmwareReleasePin[] = ${JSON.stringify(out, null, 4)};
export const PADTEST_FILES: Record<string, string> = ${JSON.stringify(files)};
`);
console.log(out.map((p) => `${p.tag} fw ${p.fwVersion} ${p.file.size} B ${p.file.sha256}`).join("\n"));
