// TEST BUILD ONLY. node scripts/gen-test-firmware.mjs <dir>
// <dir>/pins.json: [{ "tag", "kind", "fwVersion", "file", "notesUrl"? }]; the files sit beside it.
// Writes src/generated/test-pins.ts (the pins) and src/generated/embedded-test.ts (the files, base64).
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
const pins = JSON.parse(readFileSync(join(dir, "pins.json"), "utf8"));
const out = [];
const files = {};
for (const p of pins) {
    const bytes = readFileSync(join(dir, p.file));
    out.push({
        tag: p.tag, kind: p.kind, fwVersion: p.fwVersion, updaterProtocol: 4, svalProtocol: 3,
        file: { uf2: p.file, sha256: createHash("sha256").update(bytes).digest("hex"), size: bytes.length },
        notesUrl: p.notesUrl ?? "",
    });
    files[p.tag] = bytes.toString("base64");
}
writeFileSync("src/generated/test-pins.ts",
`import type { FirmwareReleasePin } from "@/constants/firmware-releases";

// TEST BUILD ONLY. Generated by scripts/gen-test-firmware.mjs.
export const TEST_PINS: FirmwareReleasePin[] = ${JSON.stringify(out, null, 4)};
`);
writeFileSync("src/generated/embedded-test.ts",
`// TEST BUILD ONLY. Generated by scripts/gen-test-firmware.mjs: the carried files, base64.
export default ${JSON.stringify(files)} as Record<string, string>;
`);
console.log(out.map((p) => `${p.tag} fw ${p.fwVersion} ${p.file.size} B ${p.file.sha256}`).join("\n"));
